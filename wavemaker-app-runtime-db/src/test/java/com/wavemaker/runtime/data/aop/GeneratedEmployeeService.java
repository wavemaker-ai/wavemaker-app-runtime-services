package com.wavemaker.runtime.data.aop;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.Pageable;

import com.wavemaker.runtime.data.annotations.EntityService;
import com.wavemaker.runtime.data.expression.QueryFilter;
import com.wavemaker.runtime.data.support.entity.Employee;

/**
 * Stands in for a generated {@code <Entity>ServiceImpl}: the class WaveMaker annotates with {@code @EntityService}
 * and that {@link CRUDAspectManager} wraps in a real app. Its CRUD methods have the same names, parameters and
 * return types as the ones generated by {@code wavemaker-studio-core/.../templates/data/service_impl.ftl}, and
 * like the generated class it declares them itself, which the aspect's {@code @within} pointcut needs. Rows are
 * kept in a map instead of a database, since the aspect only intercepts calls and publishes events.
 */
@EntityService(serviceId = "hrdb", entityClass = Employee.class)
public class GeneratedEmployeeService {

    private final Map<Long, Employee> store = new LinkedHashMap<>();

    private long nextId = 1;

    private String lastQuery;

    public Employee create(final Employee employee) {
        employee.setId(nextId++);
        store.put(employee.getId(), employee);
        return employee;
    }

    public Employee getById(final Long id) {
        return store.get(id);
    }

    public Employee findById(final Long id) {
        return store.get(id);
    }

    public Employee update(final Employee employee) {
        store.put(employee.getId(), employee);
        return employee;
    }

    public Employee delete(final Long id) {
        return store.remove(id);
    }

    public void delete(final Employee employee) {
        store.remove(employee.getId());
    }

    public Page<Employee> findAll(final QueryFilter[] queryFilters, final Pageable pageable) {
        return page(pageable);
    }

    public Page<Employee> findAll(final String query, final Pageable pageable) {
        lastQuery = query;
        return page(pageable);
    }

    /**
     * The query the last {@code findAll(String, Pageable)} call received, after any listener rewrote it.
     */
    public String getLastQuery() {
        return lastQuery;
    }

    private Page<Employee> page(final Pageable pageable) {
        List<Employee> all = new ArrayList<>(store.values());
        return new PageImpl<>(all, pageable, all.size());
    }
}
