package com.wavemaker.runtime.data.support.entity;

import java.io.Serializable;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;

/**
 * One-to-Many parent with an explicit {@code cascade}/{@code orphanRemoval} on {@link #tasks} - contrast with
 * {@link Department}'s {@code employees} association above, which has neither: removing a {@code Department}
 * through Hibernate does not touch its employees, but removing a {@code Project} removes its {@link Task}s too.
 */
@Entity
public class Project implements Serializable {

    @Id
    @GeneratedValue
    private Long id;

    private String name;

    private LocalDate startDate;

    @OneToMany(mappedBy = "project", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<Task> tasks = new ArrayList<>();

    public Long getId() {
        return id;
    }

    public void setId(final Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(final String name) {
        this.name = name;
    }

    public LocalDate getStartDate() {
        return startDate;
    }

    public void setStartDate(final LocalDate startDate) {
        this.startDate = startDate;
    }

    public List<Task> getTasks() {
        return tasks;
    }

    public void setTasks(final List<Task> tasks) {
        this.tasks = tasks;
    }
}
