-- Verified directly against the real fixtures (TemporalEmployee.java/TemporalEmployeeHistory.java) - the
-- previous version of this table had guessed-but-wrong salary/businesstimestart/businesstimeend columns that
-- don't exist on either entity. Both are deliberately minimal: id/name/active only.
CREATE TABLE temporalemployee (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255),
    active BOOLEAN
);

-- temporalemployeehistory has no employee_id FK at all - TemporalEmployeeHistory.asParent() reconstructs a
-- parent purely from its own name/active columns, with no link back to which TemporalEmployee row it came from.
CREATE TABLE temporalemployeehistory (
    historyid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255),
    active    BOOLEAN
);

-- Plain (non-temporal) one-to-many child of temporalemployee, mirroring project/task's mandatory, cascading
-- shape exactly - exists to verify cascade-delete still works when the parent is a @TableTemporal entity.
CREATE TABLE temporalemployeeaward (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES temporalemployee (id) ON DELETE CASCADE,
    awardcode  VARCHAR(50),
    awardedon  DATE
);
