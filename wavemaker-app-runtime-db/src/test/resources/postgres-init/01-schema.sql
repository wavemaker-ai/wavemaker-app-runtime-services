-- Mirrors the fixture entities under com.wavemaker.runtime.data.support.entity, used by every
-- AbstractHibernateIntegrationTest subclass. Hibernate itself never quotes identifiers in its generated DDL, and
-- Postgres folds every unquoted identifier to lower case - so "hireDate" becomes "hiredate" at the physical
-- table level regardless of the Java field's camelCase name. Every name below is written lower case, unquoted,
-- for exactly that reason: it's what Hibernate's own auto-DDL would produce against this same database.
--
-- VERIFY BEFORE RELYING ON THIS: Employee/Department/EmployeeAward below are transcribed directly from fixture
-- source read earlier in this session. temporalemployee/temporalemployeehistory are a best-effort
-- reconstruction only (the exact fixture fields weren't re-read before writing this) - re-check both against
-- the real TemporalEmployee.java/TemporalEmployeeHistory.java once they're unshelved, before trusting this
-- schema for temporal-dao testing specifically.

CREATE TABLE department (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255),
    location VARCHAR(255)
);

-- department_id has no ON DELETE clause, so it defaults to RESTRICT - a department with employees still
-- pointing at it cannot be deleted at all. manager_id is self-referencing (employee -> employee) with
-- ON DELETE SET NULL instead - deliberately a different cascade style, on purpose: deleting a manager must
-- not cascade-delete their reports, just detach them.
CREATE TABLE employee (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255),
    salary        NUMERIC(19, 2),
    hiredate      DATE,
    active        BOOLEAN,
    department_id BIGINT REFERENCES department (id),
    manager_id    BIGINT REFERENCES employee (id) ON DELETE SET NULL
);

CREATE TABLE employeeaward (
    employeeid BIGINT REFERENCES employee (id),
    awardcode VARCHAR(50),
    awardedon DATE,
    PRIMARY KEY (employeeid, awardcode)
);

-- One-to-One: shares its primary key with employee rather than having an independent id/unique FK column -
-- the classic "shared PK" 1:1 pattern. ON DELETE CASCADE here (contrast with manager_id above): a profile
-- has no meaning without its employee, so it SHOULD disappear when the employee does.
CREATE TABLE employee_profile (
    employee_id BIGINT PRIMARY KEY REFERENCES employee (id) ON DELETE CASCADE,
    bio         VARCHAR(500),
    address     VARCHAR(255)
);

-- One-to-One, second style: a SEPARATE unique FK column + its own surrogate id, rather than sharing
-- employee's PK (contrast with employee_profile above). This is the more common 1:1 shape in practice,
-- used whenever the child side might need to be referenced independently of its parent.
CREATE TABLE employee_badge (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id  BIGINT UNIQUE NOT NULL REFERENCES employee (id) ON DELETE CASCADE,
    badge_number VARCHAR(20) NOT NULL
);

-- Self-referencing Many-to-Many: symmetric peer links between employees (e.g. "collaborates closely
-- with"), as opposed to manager_id's directed, hierarchical self-reference above. Modeled as a single
-- directional row per pair - add the reverse row too if the mapping needs to be navigable from either side.
CREATE TABLE employee_peer (
    employee_id BIGINT REFERENCES employee (id) ON DELETE CASCADE,
    peer_id     BIGINT REFERENCES employee (id) ON DELETE CASCADE,
    PRIMARY KEY (employee_id, peer_id),
    CHECK (employee_id <> peer_id)
);

-- One-to-Many parent-child with an EXPLICIT ON DELETE CASCADE - contrast with department/employee above
-- (implicit RESTRICT): deleting a project takes all of its tasks with it, no detach-and-orphan step needed.
-- project_id is also NOT NULL (contrast with employee.department_id, which is nullable/optional) - a task
-- cannot exist without a project, whereas an employee can exist without a department.
CREATE TABLE project (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255),
    startdate DATE
);

CREATE TABLE task (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    title      VARCHAR(255),
    done       BOOLEAN DEFAULT FALSE
);

-- Many-to-Many: a pure join table with no identity/entity of its own (composite PK only, no separate id
-- column) - the structural signal that distinguishes a true M:M join from a third real entity. Both FKs
-- cascade: removing either side only ever cleans up the join row, never the other side's real data.
CREATE TABLE employee_project (
    employee_id BIGINT REFERENCES employee (id) ON DELETE CASCADE,
    project_id  BIGINT REFERENCES project (id) ON DELETE CASCADE,
    role        VARCHAR(100),
    PRIMARY KEY (employee_id, project_id)
);

-- Many-to-Many modeled as its OWN entity instead of a pure join table (contrast with employee_project
-- above) - needed once the relationship itself needs a surrogate id or more than a couple of flat
-- attributes (here: assigned_on/hours_logged). This is the "association class" pattern.
CREATE TABLE task_assignment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      BIGINT NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    employee_id  BIGINT NOT NULL REFERENCES employee (id) ON DELETE CASCADE,
    assigned_on  DATE,
    hours_logged NUMERIC(5, 2) DEFAULT 0
);

